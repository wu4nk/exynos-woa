"""rescale_splash.py - the boot screen for the Galaxy S10 (1440 x 3040) from the S10e's BootSplash.h (1080 x 2280).

    python rescale_splash.py IN_HEADER OUT_HEADER [PREVIEW.png]

1440 x 3040 is exactly 4/3 of 1080 x 2280 in both directions, so the S10e splash (make_splash.py, rendered with
Windows fonts on the upstream build PC) is decoded, scaled by 4/3 (Lanczos) and encoded again in the same format
(per row, little-endian 16-bit tokens: bit 15 clear = that many black pixels; bit 15 set = (token & 0x7FFF) literal
pixels follow as B, G, R bytes). Near-black pixels from the filter are snapped to black so the runs stay long.
"""
import re
import sys

from PIL import Image

SW, SH, DW, DH = 1080, 2280, 1440, 3040


def decode(path):
    txt = open(path).read()
    body = txt[txt.index('{') + 1:txt.rindex('}')]
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))
    img = Image.new('RGB', (SW, SH))
    px = img.load()
    pos = 0
    for y in range(SH):
        x = 0
        while x < SW:
            tok = data[pos] | data[pos + 1] << 8
            pos += 2
            n = tok & 0x7FFF
            if tok & 0x8000:
                for i in range(n):
                    b, g, r = data[pos:pos + 3]
                    px[x + i, y] = (r, g, b)
                    pos += 3
            x += n
    assert pos == len(data), (pos, len(data))
    return img


def encode(img):
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        x = 0
        while x < w:
            if px[x, y] == (0, 0, 0):
                n = 0
                while x + n < w and n < 0x7FFF and px[x + n, y] == (0, 0, 0):
                    n += 1
                out += bytes((n & 0xFF, n >> 8))
            else:
                n = 0
                while x + n < w and n < 0x7FFF and px[x + n, y] != (0, 0, 0):
                    n += 1
                t = n | 0x8000
                out += bytes((t & 0xFF, t >> 8))
                for i in range(n):
                    r, g, b = px[x + i, y]
                    out += bytes((b, g, r))
            x += n
    return out


def main():
    src = decode(sys.argv[1])
    dst = src.resize((DW, DH), Image.LANCZOS)
    dst = dst.point(lambda v: 0 if v < 6 else v)   # snap filter ringing near black
    p = dst.load()
    for y in range(DH):
        for x in range(DW):
            if max(p[x, y]) < 6:
                p[x, y] = (0, 0, 0)
    data = encode(dst)
    lines = ['// Generated by firmware/tools/bootsplash/rescale_splash.py from BootSplash.h (S10e 1080 x 2280, x 4/3)',
             '// for the Galaxy S10 - do not edit (see make_splash.py for the encoding).',
             '#define BOOT_SPLASH_WIDTH   %d' % DW, '#define BOOT_SPLASH_HEIGHT  %d' % DH,
             'STATIC CONST UINT8  mBootSplash[%d] = {' % len(data)]
    for i in range(0, len(data), 24):
        lines.append('  ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',')
    lines.append('};')
    open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
    if len(sys.argv) > 3:
        dst.save(sys.argv[3])
    print('splash %dx%d: %d bytes' % (DW, DH, len(data)))


if __name__ == '__main__':
    main()
