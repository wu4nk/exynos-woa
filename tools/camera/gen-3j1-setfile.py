#!/usr/bin/env python3
"""gen-3j1-setfile.py - turn Samsung's S5K3J1 setfile A (GPL-2.0, LineageOS exynos9820 kernel:
drivers/media/platform/exynos/fimc-is2/sensor/module_framework/cis/fimc-is-cis-3j1-setA.h) into
drivers/S10eCam/S10eCam3j1.h for S10eCam's stage 4.

  python3 tools/camera/gen-3j1-setfile.py <path to fimc-is-cis-3j1-setA.h> > drivers/S10eCam/S10eCam3j1.h

Each kernel entry is {addr, data, size}. size 2 -> {addr, data} (16-bit write); I2C_MODE_DELAY -> {0xFFFF, us};
I2C_MODE_BURST_ADDR {0x6F12} + I2C_MODE_BURST_DATA {word} -> {0x6F12, word} each (a burst is one I2C message to
0x6F12, whose indirect pointer auto-increments per word - the same as single writes; S10eCam re-batches consecutive
0x6F12 words into FIFO-sized messages). Any other size (8-bit writes) is refused: the two tables used have none.
"""
import re, sys

TABLES = [('S10eCam3j1Global', 'sensor_3j1_setfile_A_Global'),
          ('S10eCam3j1Mode1824', 'sensor_3j1_setfile_A_1824x1368_30fps')]

src = open(sys.argv[1]).read()


def table(name):
    m = re.search(r'const u32 ' + name + r'\[\] = \{(.*?)\};', src, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    toks = [t.strip() for t in body.split(',') if t.strip()]
    assert len(toks) % 3 == 0, name
    return [toks[i:i + 3] for i in range(0, len(toks), 3)]


print('/*')
print(' * S10eCam3j1.h - GENERATED by tools/camera/gen-3j1-setfile.py from Samsung\'s fimc-is-cis-3j1-setA.h')
print(' * (S5K3J1S_EVT0_Ver_0.10_1800718_forVendor; LineageOS exynos9820 kernel, GPL-2.0). Do not edit by hand.')
print(' * {addr, value}: a 16-bit register write; addr 0xFFFF = a delay of value microseconds.')
print(' * SPDX-License-Identifier: GPL-2.0')
print(' */')
print('#pragma once\n')
print('typedef struct _S10E_REG16 { unsigned short Addr, Val; } S10E_REG16;')
print('#define S10E_REG_DELAY 0xFFFFu\n')
for cname, kname in TABLES:
    out = []
    burst_addr = None
    for a, d, z in table(kname):
        if a == 'I2C_MODE_DELAY':
            out.append((0xFFFF, int(d, 0)))
        elif a == 'I2C_MODE_BURST_ADDR':
            burst_addr = int(d, 0)
        elif a == 'I2C_MODE_BURST_DATA':
            assert burst_addr is not None
            out.append((burst_addr, int(d, 0)))
        else:
            assert z == '0x02', (kname, a, d, z)
            burst_addr = None
            out.append((int(a, 0), int(d, 0)))
    assert all(v <= 0xFFFF and r <= 0xFFFF for r, v in out)
    print('/* %s: %d writes */' % (kname, len(out)))
    print('static const S10E_REG16 %s[] = {' % cname)
    for i in range(0, len(out), 6):
        print('    ' + ' '.join('{0x%04X, 0x%04X},' % e for e in out[i:i + 6]))
    print('};\n')
